# First word comes before second word
print(f"'yes' comes before 'zoo': {'yes' < 'zoo'}")
print(f"'apple' comes before 'banana': {'apple' < 'banana'}")
print(f"'zane' comes before 'zune': {'zane' < 'zune'}")
print(f"'dog' comes before 'hamster': {'dog' < 'hamster'}")
print(f"'angel' comes before 'lilyana': {'angel' < 'lilyana'}")

# First word comes after the second word
print(f"'angel' comes after 'Lilyana': {'angel' > 'Lilyana'}")
print(f"'sad' comes after 'happy': {'sad' > 'happy'}")
print(f"'egg' comes after 'chicken': {'egg' > 'chicken'}")
print(f"'dog' comes after 'bone': {'dog' > 'bone'}")
print(f"'Samsung' comes after 'Apple': {'Samsung' > 'Apple'}")

